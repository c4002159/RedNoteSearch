export function toneKey(value: string): string {
  return (
    [...value.normalize("NFKC")]
      .filter((char) => char.charCodeAt(0) < 28 || char.charCodeAt(0) > 31)
      .map((char) =>
        /[\u13a0-\u13ff\uab70-\uabbf]/u.test(char)
          ? char.toUpperCase()
          : (CASE_FOLD.get(char) ?? char.toLowerCase()),
      )
      .join("")
      // Python str.isspace additionally includes U+001C–001F; JS \s also
      // removes U+FEFF, which Python preserves, so use White_Space explicitly.
      .replace(/[\p{White_Space}\p{P}]/gu, (char) =>
        // Preserve characters Python 16 treats as unassigned when JS uses
        // a newer Unicode punctuation table.
        CASE_FOLD.get(char) === char ? char : "",
      )
  )
}

export function uniqueTones<T extends { tone: string }>(items: T[]): T[] {
  const seen = new Set<string>()
  return items.filter(({ tone }) => {
    const key = toneKey(tone)
    if (!key || seen.has(key)) return false
    seen.add(key)
    return true
  })
}
